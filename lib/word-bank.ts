export function pickWordPair(topicCategory: string): {
  civilianWord: string;
  spyWord: string;
} {
  let pool: [string, string][];
  if (topicCategory === "mixed" || !WORD_PAIRS[topicCategory]) {
    pool = Object.values(WORD_PAIRS).flat();
  } else {
    pool = WORD_PAIRS[topicCategory];
  }
  const [civilianWord, spyWord] =
    pool[Math.floor(Math.random() * pool.length)];
  return { civilianWord, spyWord };
}
